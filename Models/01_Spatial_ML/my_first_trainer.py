# जरूरी टूल्स (Libraries) को इम्पोर्ट करें
import numpy as np                          # नंबर्स और मैट्रिक्स के साथ काम करने के लिए
import joblib                                # मॉडल को फाइल में सेव करने के लिए
from sklearn.ensemble import RandomForestClassifier   # हमारा AI क्लासिफायर (पेड़ों का जंगल)
from sklearn.metrics import accuracy_score  # एक्यूरेसी नापने के लिए

print("--- स्टेप 1: डेटा लोड कर रहे हैं ---")
# मान लीजिए हमारे पास 4 जगहों का डेटा है
# फीचर्स: [रडार बदलाव (Delta Sigma0), ऊंचाई (Elevation), ढलान (Slope)]
X_data = np.array([
    [+2.6, 44.5, 0.4],   # जगह 1: राजेंद्र नगर (गहरा पानी, नीची जमीन)
    [+2.4, 45.1, 0.5],   # जगह 2: कंकड़बाग (गहरा पानी, नीची जमीन)
    [-0.3, 52.8, 1.6],   # जगह 3: दानापुर (सूखा, ऊंची जमीन)
    [+0.4, 50.1, 1.1],   # जगह 4: गांधी मैदान (थोड़ा पानी, मध्यम ऊंचाई)
])

# टारगेट (y): 1 का मतलब 'बाढ़ आई', 0 का मतलब 'बाढ़ नहीं आई'
y_data = np.array([1, 1, 0, 0])

print(f"डेटा का आकार (Shape): {X_data.shape[0]} जगहें, {X_data.shape[1]} फीचर्स")

print("\n--- स्टेप 2 और 3: मॉडल चुनना ---")
# हम रैंडम फॉरेस्ट मॉडल बना रहे हैं जिसमें 10 निर्णय वृक्ष (Decision Trees) हैं
mera_ai = RandomForestClassifier(n_estimators=10, random_state=42)

print("\n--- स्टेप 4: मॉडल को सिखाना (TRAINING / FIT) ---")
# .fit() ही वह जादुई फंक्शन है जहाँ मॉडल डेटा देखकर पैटर्न सीखता है!
mera_ai.fit(X_data, y_data)
print("बधाई! मॉडल ने ट्रेनिंग पूरी कर ली है।")

print("\n--- स्टेप 5: नए अनजान इलाके पर टेस्ट करना (PREDICTION) ---")
# अब हम मॉडल को एक नया इलाका देते हैं जिसे उसने पहले कभी नहीं देखा:
# नया इलाका: रडार बदलाव = +2.5 dB, ऊंचाई = 44.8 m, ढलान = 0.45° (सैदपुर नाला के पास)
naya_ilaaka = np.array([[+2.5, 44.8, 0.45]])

# मॉडल से पूछें कि यहाँ बाढ़ आएगी या नहीं
faisla = mera_ai.predict(naya_ilaaka)
probability = mera_ai.predict_proba(naya_ilaaka)[0, 1]

print(f"नए इलाके के लिए AI का फैसला : {'बाढ़ (FLOOD)' if faisla[0] == 1 else 'सुरक्षित (SAFE)'}")
print(f"बाढ़ की संभावना (Probability): {probability * 100:.1f}%")

# मॉडल को डिस्क पर सेव कर लें ताकि बाद में बिना दोबारा ट्रेन किए उपयोग कर सकें
joblib.dump(mera_ai, "mera_pehle_model.joblib")
print("मॉडल 'mera_pehle_model.joblib' के नाम से सेव हो गया!")

